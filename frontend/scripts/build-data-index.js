/* ═══════════════════════════════════════════════════════════════════
   build-data-index.js — lookup indexes for the public website.
   ───────────────────────────────────────────────────────────────────
   The website loads blog articles and country/city data on demand
   (see src/data/lazyData.js) so the home page doesn't ship ~8 MB of
   content. Routing and the blog listing still need to know what
   exists, so this script writes two generated files:

     src/data/generated/routeIndex.js  (small, in the main bundle)
       /homeschool-<slug> → which data module(s) define that slug,
       the COUNTRIES slugs used by /online-school/<slug>, and one
       import() per articlesPartN.js.

     src/data/generated/articlesIndex.js  (loaded by blog routes only)
       slug → listing fields (title, category, excerpt, image, date…),
       meta title/description, and which part file holds the article.

   Runs before every `npm run dev` and `npm run build`, so the indexes
   can't drift from the data files. Never edit the generated files.
═══════════════════════════════════════════════════════════════════ */

import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const DATA = join(__dirname, '..', 'src', 'data')
const OUT = join(DATA, 'generated')

const load = (file) => import(pathToFileURL(join(DATA, file)).href)
const HEADER = '/* eslint-disable */\n// GENERATED by scripts/build-data-index.js — do not edit by hand.\n\n'

// ── Articles ─────────────────────────────────────────────────────────
// fullArticles.js is the canonical list of part files and their order
// (a later part overrides an earlier one for the same slug).
const partFiles = [...readFileSync(join(DATA, 'fullArticles.js'), 'utf8')
  .matchAll(/from '\.\/(articlesPart\d+)\.js'/g)].map(m => m[1])

const articles = {}
for (const part of partFiles) {
  const mod = await load(part + '.js')
  const obj = Object.values(mod)[0]
  for (const [slug, a] of Object.entries(obj)) {
    const intro = a.intro || ''
    articles[slug] = {
      part,
      cat: a.cat,
      country: a.country || 'kenya',
      img: a.img,
      splash: a.splash || null,
      t: a.t,
      date: a.date,
      author: a.author,
      role: a.role,
      ex: intro.length > 150 ? intro.slice(0, 147) + '…' : intro,
      featured: !!a.featured,
      metaTitle: a.metaTitle || null,
      metaDesc: a.metaDesc || intro.slice(0, 158),
    }
  }
}

// ── /homeschool-<slug> routing ───────────────────────────────────────
// Every module the /homeschool-* route resolver searches: the per-country
// *Cities.js files plus US states and Canadian provinces. Arrays of
// { slug } and slug-keyed objects both count; *_COUNTRY, *_LIST and
// *_BY_* exports are lookups over the same data and are skipped.
const slugModules = readdirSync(DATA)
  .filter(f => /Cities\.js$/.test(f) || f === 'usStates.js' || f === 'caProvinces.js')
  .sort()

const homeschool = {}
for (const file of slugModules) {
  const key = file.replace(/\.js$/, '')
  const mod = await load(file)
  const slugs = new Set()
  for (const [name, val] of Object.entries(mod)) {
    if (/_COUNTRY$|_LIST$|_BY_/.test(name) || !val || typeof val !== 'object') continue
    if (Array.isArray(val)) val.forEach(c => c && c.slug && slugs.add(c.slug))
    else Object.keys(val).forEach(s => slugs.add(s))
  }
  for (const s of slugs) (homeschool[s] ||= []).push(key)
}

const { COUNTRIES } = await load('countries.js')
const countrySlugs = COUNTRIES.map(c => c.slug)

// ── Write ────────────────────────────────────────────────────────────
mkdirSync(OUT, { recursive: true })

writeFileSync(join(OUT, 'articlesIndex.js'),
  HEADER + `export const ARTICLES_INDEX = ${JSON.stringify(articles)}\n`)

// Group slugs by module list so the file stays compact.
const byModules = {}
for (const [slug, mods] of Object.entries(homeschool)) (byModules[mods.join(',')] ||= []).push(slug)
const loaders = partFiles.map(p => `  ${p}: () => import('../${p}.js'),`).join('\n')
writeFileSync(join(OUT, 'routeIndex.js'),
  HEADER +
  `export const ARTICLE_PART_LOADERS = {\n${loaders}\n}\n\n` +
  `// module list (comma-separated) → space-separated slugs\n` +
  `const HOMESCHOOL = ${JSON.stringify(Object.fromEntries(Object.entries(byModules).map(([m, s]) => [m, s.join(' ')])), null, 1)}\n\n` +
  `export const HOMESCHOOL_SLUG_MODULES = new Map()\n` +
  `for (const [mods, slugs] of Object.entries(HOMESCHOOL)) for (const s of slugs.split(' ')) HOMESCHOOL_SLUG_MODULES.set(s, mods.split(','))\n\n` +
  `export const COUNTRY_SLUGS = new Set(${JSON.stringify(countrySlugs)})\n`)

console.log(`[data-index] ${Object.keys(articles).length} articles from ${partFiles.length} parts, ` +
  `${Object.keys(homeschool).length} /homeschool- slugs from ${slugModules.length} modules, ${countrySlugs.length} countries`)
