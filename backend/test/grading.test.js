const { test } = require('node:test')
const assert = require('node:assert')
const { gradeFor, scaleKey, keyLine, wordFor } = require('../src/lib/grading')

test('each curriculum grades in its own language', () => {
  assert.equal(gradeFor('CambridgeIGCSE', 85), 'A')
  assert.equal(gradeFor('CambridgeIGCSE', 92), 'A*')
  assert.equal(gradeFor('CambridgeIGCSE', 25), 'G')
  assert.equal(gradeFor('EdexcelIGCSE', 92), '9')
  assert.equal(gradeFor('AQAGCSE', 47), '4')
  assert.equal(gradeFor('CambridgeALevel', 41), 'E')
  assert.equal(gradeFor('CambridgeALevel', 30), 'U')
  assert.equal(gradeFor('IBDP', 86), '7')
  assert.equal(gradeFor('IBMYP', 50), '4')
  assert.equal(gradeFor('American', 91), 'A-')
  assert.equal(gradeFor('American', 55), 'F')
  assert.equal(gradeFor('Canadian', 45), 'R')
  assert.equal(gradeFor('KenyaCBE', 76), 'EE')
  assert.equal(gradeFor('KenyaCBE', 60), 'ME')
  assert.equal(gradeFor('KenyaCBE', 10), 'BE')
  assert.equal(gradeFor('KCSE', 72), 'B+')
  assert.equal(gradeFor('KCSE', 20), 'E')
  assert.equal(gradeFor('CambridgePrimary', 72), 'Secure')
})

test('legacy names and BNC stages resolve', () => {
  assert.equal(scaleKey('KenyaCBC'), 'cbe')
  assert.equal(scaleKey('IGCSE'), 'igcse')
  assert.equal(scaleKey('A-Level'), 'alevel')
  assert.equal(scaleKey('BNC', 'Year 11'), 'gcse9')
  assert.equal(scaleKey('BNC', 'Year 12 (Sixth Form)'), 'alevel')
  assert.equal(scaleKey('BNC', 'Year 4'), 'descriptive')
  assert.equal(scaleKey('BNC', 'Reception'), 'descriptive')
})

test('no score gives a dash; the key line and words read correctly', () => {
  assert.equal(gradeFor('CambridgeIGCSE', null), '—')
  assert.equal(gradeFor('KCSE', undefined), '—')
  assert.match(keyLine('KenyaCBE'), /^CBE levels: EE 75\+ · ME 50\+ · AE 25\+ · BE <25$/)
  assert.equal(wordFor('KenyaCBE', 'ME'), 'Meeting expectations')
})
